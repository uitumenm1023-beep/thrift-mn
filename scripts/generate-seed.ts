// Generates supabase/seed.sql (and the all-in-one supabase/setup.sql)
// from src/lib/demo-data.ts.
// Run with:  npm run seed:generate   (Node 22.6+ runs TypeScript directly)

import { readFileSync, writeFileSync } from "node:fs";
import {
  DEMO_CATEGORIES,
  DEMO_PRODUCTS,
  DEMO_PRODUCT_IMAGES,
  DEMO_SHOPS,
} from "../src/lib/demo-data.ts";

const q = (v: string | number | boolean | null) => {
  if (v === null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};

const rows = (values: (string | number | boolean | null)[][]) =>
  values.map((r) => `  (${r.map(q).join(", ")})`).join(",\n");

const sql = `-- =====================================================================
-- Thrift.mn — DEMONSTRATION DATA (generated by scripts/generate-seed.ts)
-- All rows are marked is_demo = true. Safe to re-run: it replaces the
-- demo shops/products (never real ones) and refreshes category images.
-- Remove demo data later with:
--   delete from public.shops where is_demo;   (products/images cascade)
-- =====================================================================

-- Start from a clean slate for demo rows only (products/images cascade).
delete from public.shops where is_demo = true;

insert into public.categories (id, name, slug, image_url, sort_order) values
${rows(DEMO_CATEGORIES.map((c) => [c.id, c.name, c.slug, c.image_url, c.sort_order]))}
on conflict (slug) do update
  set name = excluded.name, image_url = excluded.image_url, sort_order = excluded.sort_order;

insert into public.shops (id, owner_id, name, description, logo_url, cover_url, phone, instagram_url, facebook_url, address, district, status, is_demo, created_at) values
${rows(DEMO_SHOPS.map((s) => [s.id, null, s.name, s.description, s.logo_url, s.cover_url, s.phone, s.instagram_url, s.facebook_url, s.address, s.district, s.status, true, s.created_at]))}
on conflict (id) do nothing;

insert into public.products (id, shop_id, category_id, name, description, price, size, condition, is_available, is_demo, created_at) values
${rows(DEMO_PRODUCTS.map((p) => [p.id, p.shop_id, p.category_id, p.name, p.description, p.price, p.size, p.condition, p.is_available, true, p.created_at]))}
on conflict (id) do nothing;

insert into public.product_images (id, product_id, image_url, display_order) values
${rows(DEMO_PRODUCT_IMAGES.map((i) => [i.id, i.product_id, i.image_url, i.display_order]))}
on conflict (id) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("✓ supabase/seed.sql written");

// setup.sql = every migration + the seed, for pasting into the SQL Editor once.
const parts = [
  "migrations/0001_schema.sql",
  "migrations/0002_rls.sql",
  "migrations/0003_storage.sql",
  "seed.sql",
];
const setup =
  "-- Thrift.mn: full setup in one file (schema + RLS + storage + demo seed).\n" +
  "-- Paste into Supabase → SQL Editor → Run. Safe to run more than once.\n" +
  "-- Generated by scripts/generate-seed.ts — edit the source files instead.\n" +
  parts
    .map((f) => `\n-- ===================== supabase/${f} =====================\n` +
      readFileSync(new URL(`../supabase/${f}`, import.meta.url), "utf8"))
    .join("");
writeFileSync(new URL("../supabase/setup.sql", import.meta.url), setup);
console.log("✓ supabase/setup.sql written");
